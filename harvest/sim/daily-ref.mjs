// v4.0 每日挑战: reference scores for every remix (cleared level × twist).
// The balance bot (sharp profile) plays each remix for the 3-minute limit with a neutral season;
// the median money earned over 3 seeds is the reference ("gold" = 100%, silver 75%, bronze 45%).
//   node sim/daily-ref.mjs          # print the table
//   node sim/daily-ref.mjs --write  # also write js/daily-ref.js
import fs from 'fs';
import { CFG } from '../js/config.js';
import { World } from '../js/world.js';
import { buildLevel, worldOpts, swapMap, TWIST_IDS } from '../js/daily.js';

const DT = 1 / 30;
function play(li, twist, seed) {
  const w = new World(li, { quiet: true, seed, level: buildLevel(li, twist), daily: { twist }, timeLimit: CFG.daily.time, ...worldOpts(twist) });
  const p = w.player; let target = null, think = 0;
  while (!w.won) {
    think -= DT; if (think <= 0) { target = w.guide(); think = 0.1; }
    if (target && (target.kind === 'pile' || target.kind === 'field')) target = w.guide() || target;
    let ix = 0, iy = 0;
    if (target) {
      const stop = target.kind === 'tile' ? 4 : target.kind === 'pile' || target.kind === 'field' ? 2 : 6;
      if (Math.hypot(target.x - p.x, target.y - p.y) > stop) { const wp = w.steer(p, target.x, target.y); const dx = wp.x - p.x, dy = wp.y - p.y, d = Math.hypot(dx, dy) || 1; ix = dx / d; iy = dy / d; }
    }
    w.update(DT, ix, iy);
  }
  return w.score;
}
const ref = {}; let bad = 0;
for (let li = 1; li < CFG.levels.length; li++) {
  const row = [];
  for (const tw of TWIST_IDS) {
    if (tw === 'swap' && !Object.keys(swapMap(li)).length) continue;
    const s = [1, 2, 3].map((k) => play(li, tw, k * 777 + li)).sort((a, b) => a - b)[1];
    ref[`${li}:${tw}`] = s; row.push(`${tw} ${s}`);
    if (!(s > 0)) bad++;
  }
  console.log(`第${li + 1}关 ${CFG.levels[li].name}: ${row.join(' · ')}`);
}
console.log(bad ? `FAIL: ${bad} remixes earned nothing` : 'OK: every remix earns money in 3 minutes');
if (process.argv.includes('--write')) {
  fs.writeFileSync(new URL('../js/daily-ref.js', import.meta.url), `// generated by sim/daily-ref.mjs — bot earnings (median of 3 seeds) in each 3-minute 每日挑战 remix, key "level index:twist"\nexport const DAILY_REF = ${JSON.stringify(ref)};\n`);
  console.log('wrote js/daily-ref.js');
}
if (bad) process.exit(1);
